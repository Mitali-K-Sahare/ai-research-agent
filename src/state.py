"""
=============================================================================
Project 3: AI Research Agent
state.py — The Graph's Shared Memory
=============================================================================

WHAT THIS FILE DOES:
  Defines ResearchState — a TypedDict that every node in the LangGraph
  workflow reads from and writes to. This is the graph's "shared memory."

HOW IT WORKS (Week 11 review):
  - Each node function receives the current state as input
  - Each node returns a dictionary with ONLY the fields it wants to update
  - LangGraph merges the updates into the state automatically

THE ANNOTATED TRICK:
  Some fields (like "sources") need to ACCUMULATE across multiple nodes.
  Without Annotated, returning {"sources": [new_item]} would OVERWRITE
  the entire list. With Annotated[list, operator.add], LangGraph APPENDS
  the new items to the existing list instead. This is how the search_node
  can run multiple times and build up sources gradually.
=============================================================================
"""

# ── IMPORTS ─────────────────────────────────────────────────────────────────

# TypedDict lets us define a dictionary with specific key names and types
# It's like a blueprint: "this dictionary MUST have these keys with these types"
# Week 11 used this same pattern for graph state
from typing import TypedDict

# Annotated lets us attach extra behavior to a type
# We use it to tell LangGraph: "when updating this list, APPEND don't OVERWRITE"
from typing import Annotated

# operator.add is Python's built-in addition function
# For lists: operator.add([1, 2], [3]) → [1, 2, 3] (concatenation)
# LangGraph uses this as the "reducer" — how to merge old + new values
import operator


# ============================================================
# RESEARCH STATE
# ============================================================
# This is the COMPLETE state of a research run.
# Every piece of information the agent tracks lives here.

class ResearchState(TypedDict):

    # ── The Research Topic ──────────────────────────────────────
    # What the user wants to research
    # Set once at the start, never changes
    topic: str

    # ── Planning ────────────────────────────────────────────────
    # Search queries generated by the plan_node
    # Annotated with operator.add so review_node can ADD more queries
    # without losing the original ones
    search_queries: Annotated[list, operator.add]

    # ── Search Results ──────────────────────────────────────────
    # Raw search results: each item is a dict with "title", "url", "snippet"
    # Annotated so each search_node run APPENDS new results
    sources: Annotated[list, operator.add]

    # ── Extracted Findings ──────────────────────────────────────
    # Key information extracted from fetched web pages
    # Each item is a string with the important content from one source
    # Annotated so findings accumulate across multiple search iterations
    findings: Annotated[list, operator.add]

    # ── The Report ──────────────────────────────────────────────
    # The synthesized research report (markdown formatted)
    # Created by synthesize_node, may be updated if review triggers re-synthesis
    report_content: str

    # ── Confidence Ratings ──────────────────────────────────────
    # Each claim's confidence: "VERIFIED", "INFERRED", or "UNCERTAIN"
    # Populated by synthesize_node as part of report generation
    confidence_scores: Annotated[list, operator.add]

    # ── Review Results ──────────────────────────────────────────
    # Quality score (1-10) assigned by the review_node
    review_score: int

    # Written feedback from the reviewer about what's good and what's missing
    review_feedback: str

    # ── Loop Control ────────────────────────────────────────────
    # Tracks which search query we're currently processing
    # Incremented by search_node each time it runs
    # Used by should_continue_searching() to decide: loop or move on
    search_iteration: int
